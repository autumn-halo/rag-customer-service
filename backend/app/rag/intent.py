"""意图识别：区分"商品/售后咨询"与"闲聊/通用问题"。

路由策略（检索优先，关键词兜底）：
1. 检索相关度 ≥ 阈值 → 严格模式带引用作答（数据说话，覆盖任何措辞的商品问题）
2. 相关度不足时，用本模块的关键词判断：
   - 商品/售后关键词 → 兜底话术（防瞎编）
   - 其他 → 自由对话（"你是什么大模型"这类问题自然回答）

关键词只在"没查到资料"时兜底判断，是工程折中：零成本、可解释、可测试；
更精准的方案是用小模型做意图分类（写入 README 后续规划）。
"""

PRODUCT_KEYWORDS = (
    # 售后
    "退货", "退款", "退换", "换货", "退钱", "售后", "保修", "维修", "发票", "退差价",
    # 物流
    "发货", "物流", "快递", "运费", "包邮", "签收", "配送",
    # 商品
    "商品", "产品", "型号", "参数", "规格", "尺寸", "尺码", "颜色", "材质",
    "质量", "保质期", "有效期", "库存", "有货", "缺货",
    # 交易
    "价格", "多少钱", "优惠", "折扣", "促销", "满减", "下单", "订单",
    "支付", "付款", "购买",
    # 客服
    "客服", "人工",
    # 单字（覆盖口语化提问，如"你们卖xx吗"；误判代价只是走严格模式，可控）
    "卖", "买", "货", "款", "价",
)


def is_product_question(text: str) -> bool:
    """判断提问是否与商品/售后相关。"""
    return any(kw in text for kw in PRODUCT_KEYWORDS)
