def main() -> None:
    parser = argparse.ArgumentParser(description="灌入演示知识库语料")
    parser.add_argument("--host", default="http://localhost:8000")
    args = parser.parse_args()

    # 1. 管理员登录
    r = httpx.post(
        f"{args.host}/api/auth/login",
        json={"username": "admin", "password": "123456"},
        timeout=15,
    )
    if r.status_code != 200:
        sys.exit(f"❌ 管理员登录失败（{r.status_code}）：{r.text[:200]}\n请确认服务已启动且 admin 密码未修改")
    headers = {"Authorization": f"Bearer {r.json()['access_token']}"}
    print("✅ 管理员登录成功")

    # 2. 上传全部演示文档
    for filename, content in DEMO_DOCS.items():
        r = httpx.post(
            f"{args.host}/api/documents/upload",
            files={"files": (filename, content.encode("utf-8"), "text/plain")},
            headers=headers,
            timeout=30,
        )
        if r.status_code == 201:
            print(f"  ⬆️  已上传：{filename}")
        else:
            print(f"  ❌ 上传失败：{filename}（{r.status_code}）{r.text[:100]}")
            sys.exit(1)

    # 3. 等待全部入库完成
    print("\n⏳ 等待后台入库完成...")
    deadline = time.time() + 180
    while time.time() < deadline:
        page = httpx.get(f"{args.host}/api/documents?size=50", headers=headers, timeout=15).json()
        pending = [d for d in page["items"] if d["status"] in ("pending", "processing")]
        failed = [d for d in page["items"] if d["status"] == "failed"]
        if not pending:
            print(f"✅ 入库完成：共 {page['total']} 篇文档")
            for d in failed:
                print(f"   ⚠️ 失败：{d['filename']} —— {d['error_message']}")
            if failed:
                sys.exit(1)
            print("\n🎉 演示数据就绪！可以开始提问了，例如：")
            print('   "你们的退货政策是怎样的？"')
            print('   "无线蓝牙耳机 Pro 续航多久？"')
            print('   "支持分期付款吗？"')
            return
        time.sleep(2)
    sys.exit("❌ 等待入库超时（3 分钟），请检查后端日志")


if __name__ == "__main__":
    main()
